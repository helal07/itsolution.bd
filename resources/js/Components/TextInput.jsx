import { forwardRef, useEffect, useImperativeHandle, useRef } from 'react';

export default forwardRef(function TextInput(
    { type = 'text', className = '', isFocused = false, ...props },
    ref,
) {
    const localRef = useRef(null);

    useImperativeHandle(ref, () => ({
        focus: () => localRef.current?.focus(),
    }));

    useEffect(() => {
        if (isFocused) {
            localRef.current?.focus();
        }
    }, [isFocused]);

    return (
        <input
            {...props}
            type={type}
            className={
                'rounded-xl border-neutral-300 bg-white text-neutral-900 shadow-sm placeholder:text-neutral-400 focus:border-primary focus:ring-2 focus:ring-primary/20 transition-all text-sm ' +
                className
            }
            ref={localRef}
        />
    );
});
